  static List<ZakatInfo> getZakatByCategory(String category) {
    return zakatTypes.where((z) => z.subcategory == category).toList();
  }

  static List<ZakatInfo> getSadaqahByCategory(String category) {
    return sadaqahTypes.where((s) => s.subcategory == category).toList();
  }

  static List<String> getZakatCategories() {
    return zakatTypes.map((z) => z.subcategory!).toSet().toList();
  }

  static List<String> getSadaqahCategories() {
    return sadaqahTypes.map((s) => s.subcategory!).toSet().toList();
